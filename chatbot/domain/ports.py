from typing import Protocol


class ProductRepository(Protocol):
    def all(self) -> list[dict]: ...
    def by_ids(self, ids: list[str]) -> list[dict]: ...
    def ping(self) -> bool: ...


class LLMProvider(Protocol):
    @property
    def enabled(self) -> bool: ...
    def plan(self, message: str, state: dict, budget=None) -> tuple[dict | None, dict]: ...
    def answer_stream(self, context: dict, budget=None): ...


class CommerceGateway(Protocol):
    def policy(self, policy_type: str) -> dict: ...
    def order(self, order_id: str, token: str) -> dict: ...
    def return_eligibility(self, order_id: str, token: str) -> dict: ...

